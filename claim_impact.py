"""Provenance-aware narrowing from changed chunks to claims and answers."""

import re

from answer_impact import find_affected_answers


STOP_WORDS = {
    "according", "answer", "all", "and", "are", "be", "by",
    "can", "customers", "for", "in", "is", "of", "on",
    "policy", "the", "to", "within"
}


def _tokens(text: str) -> set[str]:
    words = re.findall(r"[a-z0-9]+", text.lower())

    normalized = {
        word[:-1] if word.endswith("s") and len(word) > 3 else word
        for word in words
    }

    return normalized - STOP_WORDS


def _claims_for_answer(answer: dict) -> list[dict]:
    return answer.get("provenance", {}).get("claims") or [
        {
            "claim_id": "legacy_answer_claim",
            "text": answer.get("generated_answer", "")
        }
    ]


def _evidence_for_answer(answer: dict) -> list[dict]:
    """Return all evidence units stored in an answer's provenance."""
    evidence = []

    sources = answer.get("provenance", {}).get("sources", [])

    for source in sources:
        for version in source.get("versions", []):
            for item in version.get("evidence", []):
                evidence.append(item)

    return evidence


def _claim_evidence_map(answer: dict) -> dict[str, set[str]]:
    """
    Build:
        claim_id -> set of evidence_ids

    from the explicit provenance relationships.
    """
    relationships = (
        answer.get("provenance", {})
        .get("relationships", {})
        .get("claim_evidence", [])
    )

    mapping: dict[str, set[str]] = {}

    for relationship in relationships:
        claim_id = relationship.get("claim_id")
        evidence_id = relationship.get("evidence_id")

        if claim_id and evidence_id:
            mapping.setdefault(claim_id, set()).add(evidence_id)

    return mapping


def _changed_chunk_ids(changes: list[dict]) -> set[str]:
    """Collect chunk IDs from both old and new changed chunks."""
    chunk_ids = set()

    for change in changes:
        for key in ("old_chunk", "new_chunk"):
            chunk = change.get(key)

            if not chunk:
                continue

            chunk_id = chunk.get("chunk_id")

            if chunk_id:
                chunk_ids.add(chunk_id)

    return chunk_ids


def select_affected_claims(
    previous_snapshot: dict,
    changes: list[dict],
    answers: list[dict] | None = None,
) -> list[dict]:
    """
    Narrow changed source chunks to affected claims and answers.

    Priority:
    1. Exact provenance evidence/chunk match.
    2. Lexical relevance fallback for legacy/incomplete records.

    For answers with explicit claim-to-evidence provenance, the
    lexical fallback is not used for claims that already have
    linked evidence. This prevents unrelated claims from being
    selected because they share generic words with a changed chunk.
    """

    candidates = find_affected_answers(
        previous_snapshot["content_hash"],
        source_id=previous_snapshot.get("source_id"),
        answers=answers,
    )

    selections = []

    changed_chunk_ids = _changed_chunk_ids(changes)

    for change in changes:

        changed_text = " ".join(
            chunk["text"]
            for chunk in (
                change.get("old_chunk"),
                change.get("new_chunk"),
            )
            if chunk
        )

        changed_tokens = _tokens(changed_text)

        for answer in candidates:

            evidence_items = _evidence_for_answer(answer)
            claim_evidence = _claim_evidence_map(answer)

            for claim in _claims_for_answer(answer):

                claim_id = claim.get("claim_id")

                linked_evidence_ids = claim_evidence.get(
                    claim_id,
                    set(),
                )

                exact_matches = []

                # -----------------------------------------------------
                # 1. Exact provenance matching
                # -----------------------------------------------------
                for evidence in evidence_items:

                    evidence_id = evidence.get("evidence_id")
                    chunk_id = evidence.get("chunk_id")

                    if evidence_id not in linked_evidence_ids:
                        continue

                    # New provenance records have an explicit chunk_id.
                    if chunk_id:
                        if chunk_id in changed_chunk_ids:
                            exact_matches.append(evidence)
                            continue

                        # Chunk IDs may be regenerated by the source normalizer.
                        # If the ID does not match, compare the stored evidence
                        # text with the old changed chunk text.
                        evidence_text = evidence.get("text", "").strip()
                        old_chunk = change.get("old_chunk") or {}
                        old_chunk_text = old_chunk.get("text", "").strip()

                        if evidence_text and old_chunk_text:
                            if evidence_text == old_chunk_text:
                                exact_matches.append(evidence)

                        continue

                    # Legacy/incomplete provenance may not have a chunk_id.
                    # In that case, match the stored evidence text against
                    # the old changed chunk text.
                    evidence_text = evidence.get("text", "").strip()

                    old_chunk = change.get("old_chunk") or {}
                    old_chunk_text = old_chunk.get("text", "").strip()

                    if evidence_text and old_chunk_text:
                        if evidence_text == old_chunk_text:
                            exact_matches.append(evidence)

                if exact_matches:
                    selections.append(
                        {
                            "answer": answer,
                            "claim": claim,
                            "change": change,
                            "match_type": "exact_evidence",
                            "evidence": exact_matches,
                            "overlap": [],
                        }
                    )

                    continue

                # -----------------------------------------------------
                # 2. Lexical fallback
                # -----------------------------------------------------
                #
                # Only use lexical fallback when this claim has
                # no explicit evidence relationship.
                #
                # This keeps legacy/incomplete answers supported
                # while preventing false matches in new
                # multi-claim provenance records.
                # -----------------------------------------------------
                if linked_evidence_ids:
                    continue

                overlap = (
                    _tokens(claim.get("text", ""))
                    & changed_tokens
                )

                if overlap:
                    selections.append(
                        {
                            "answer": answer,
                            "claim": claim,
                            "change": change,
                            "match_type": "lexical_fallback",
                            "evidence": [],
                            "overlap": sorted(overlap),
                        }
                    )

    return selections